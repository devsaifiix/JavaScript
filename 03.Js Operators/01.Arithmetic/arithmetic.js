// Arithmetic Operators in JavaScript

document.write("<h2>Arithmetic Operators in JavaScript</h2>");

let x = 5;
let y = 2;

// Addition
let addition = x + y;
document.write("Addition (x + y): " + addition + "<br>");

// Subtraction
let subtraction = x - y;
document.write("Subtraction (x - y): " + subtraction + "<br>");

// Multiplication
let multiplication = x * y;
document.write("Multiplication (x * y): " + multiplication + "<br>");

// Division
let division = x / y;
document.write("Division (x / y): " + division + "<br>");

// Modulus
let modulus = x % y;
document.write("Modulus (x % y): " + modulus + "<br>");

// Increment
x++;
let increment = x;
document.write("Increment (++x): " + increment + "<br>");

// Decrement
y--;
let decrement = y;
document.write("Decrement (--y): " + decrement + "<br>");

// Exponentiation using Math.pow()
let power = Math.pow(x, y);
document.write("Exponentiation (Math.pow(x, y)): " + power + "<br>");

// Exponentiation using **
let power2 = x ** y;
document.write("Exponentiation (x ** y): " + power2 + "<br>");

document.write("<hr>");